// Regenerates src/translinkStops.data.ts: Translink's own ID and name for each NI Railways station, so the station
// page's ticket button can open Translink's "Plan and buy" with "From" filled. Translink's planner needs its own
// location ID (Coleraine is 10000021, "Coleraine, Coleraine Train Station"); a name alone fills the box but selects
// no station. IDs come from the planner's own location search (/locationApi/find), one station at a time.
// Usage: npm run update-translink-stops -w @dart-times/core
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SERVICES } from '../src/services';

interface Location {
  Id: string;
  Name: string;
  LocationType: string;
}

/** Stations Translink's search knows by other text: Helen's Bay only without its apostrophe, Larne Town as Larne. */
const SEARCH_AS: Record<string, string> = { NI_HELEN: 'Helens Bay', NI_LARNT: 'Larne' };
/** Stations Translink names differently: Larne Town is plain "Larne" there. */
const TRANSLINK_NAME: Record<string, string> = { NI_LARNT: 'Larne, Larne Train Station' };
/** The city is Derry: Translink's "Derry~Londonderry" is written as Derry here too. Their name is only the text shown
 *  in "From"; the ID is what selects the station. */
const tidy = (name: string) => name.replace(/Derry~Londonderry/g, 'Derry');

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
const norm = (s: string) => s.toLowerCase().replace(/[^a-z]/g, '');

async function find(text: string): Promise<Location[]> {
  for (let attempt = 0; attempt < 3; attempt++) {
    const res = await fetch(`https://www.translink.co.uk/locationApi/find?SearchString=${encodeURIComponent(text)}`, {
      signal: AbortSignal.timeout(15_000),
    });
    const data = res.ok ? ((await res.json()) as { Locations?: Location[] } | null) : null;
    if (data?.Locations) return data.Locations.filter((l) => l.LocationType === 'Train stop');
    await sleep(2000 * (attempt + 1)); // busy, or nothing for that text: wait and try again
  }
  return [];
}

/** The train stop that is this station: "<town>, <name> Train Station" ends with our name; else the only one. */
function pick(name: string, stops: Location[]): Location | undefined {
  const ours = norm(name);
  const exact = stops.filter((s) => norm(s.Name.replace(/\b(train|rail) (station|halt)\b/i, '')).endsWith(ours));
  if (exact.length) return exact.sort((a, b) => a.Name.length - b.Name.length)[0];
  const containing = stops.filter((s) => norm(s.Name).includes(ours));
  return containing.length === 1 ? containing[0] : stops.length === 1 ? stops[0] : undefined;
}

const found: Record<string, { id: string; name: string }> = {};
const unmatched: string[] = [];
for (const station of SERVICES.nir.stations) {
  let stops = await find(SEARCH_AS[station.code] ?? station.name);
  const named = TRANSLINK_NAME[station.code];
  let stop = named ? stops.find((s) => s.Name === named) : pick(station.name, stops);
  if (!stop) {
    stops = await find(`${station.name} Train Station`);
    stop = named ? stops.find((s) => s.Name === named) : pick(station.name, stops);
  }
  if (stop) found[station.code] = { id: stop.Id, name: tidy(stop.Name) };
  else unmatched.push(`${station.code} ${station.name} (train stops found: ${stops.map((s) => s.Name).join('; ') || 'none'})`);
  console.log(`${station.code.padEnd(9)} ${station.name.padEnd(24)} → ${stop ? `${stop.Id} ${tidy(stop.Name)}` : 'NOT FOUND'}`);
  await sleep(700); // go easy on Translink's site
}

const out = fileURLToPath(new URL('../src/translinkStops.data.ts', import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/update-translink-stops.ts from Translink's journey planner. Do not edit by hand.
/** Translink's location ID and name for each NI Railways station, keyed by our station code. */
export const TRANSLINK_STOPS: Record<string, { id: string; name: string }> = ${JSON.stringify(found, null, 2)};
`,
);
console.log(`\nWrote ${Object.keys(found).length} of ${SERVICES.nir.stations.length} stations to ${out}`);
if (unmatched.length) {
  console.error(`Not matched (their pages get no ticket button):\n${unmatched.map((u) => `- ${u}`).join('\n')}`);
}
