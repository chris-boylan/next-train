// Regenerates src/stations.luas.data.ts from the Luas Forecasting API's stops list (both lines, in line order).
// Usage: npm run update-luas-stops -w @dart-times/core
// Codes are the feed's with an LU_ prefix (LU_RAN), so they never clash with Irish Rail's (Connolly is CNLLY on
// Irish Rail and CON on the Luas). Names are the feed's; stations.ts tidies a few for display.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { LuasClient } from '../src/luasClient';

const stops = await new LuasClient().getStops();
const records = stops.map((s) => ({
  code: `LU_${s.abrev}`,
  name: s.name,
  apiAlias: '',
  lat: Number(s.lat.toFixed(5)),
  lon: Number(s.lon.toFixed(5)),
  line: s.line,
}));

const out = fileURLToPath(new URL('../src/stations.luas.data.ts', import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/update-luas-stops.ts from the Luas Forecasting API. Do not edit by hand.
import type { StationRecord } from './stations';

export const LUAS_STATION_DATA: (StationRecord & { line: 'red' | 'green' })[] = ${JSON.stringify(records, null, 2)};
`,
);
console.log(`Wrote ${records.length} Luas stops to ${out}`);
