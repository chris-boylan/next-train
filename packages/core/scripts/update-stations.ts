// Regenerates src/stations.data.ts from the live Irish Rail DART station list.
// Usage: npm run update-stations -w @dart-times/core
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { IrishRailClient } from '../src/irishRailClient';

const raw = await new IrishRailClient().getDartStations();
const records = raw.map((s) => ({
  code: s.StationCode.trim(),
  name: s.StationDesc.trim(),
  apiAlias: s.StationAlias.trim(),
  lat: Number(s.StationLatitude),
  lon: Number(s.StationLongitude),
}));

const out = fileURLToPath(new URL('../src/stations.data.ts', import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/update-stations.ts from the Irish Rail API. Do not edit by hand.
import type { StationRecord } from './stations';

export const DART_STATION_DATA: StationRecord[] = ${JSON.stringify(records, null, 2)};
`,
);
console.log(`Wrote ${records.length} stations to ${out}`);
