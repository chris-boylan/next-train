// Regenerates src/luasRunTimes.data.ts: how long trams take between neighbouring Luas stops, from the NTA's Luas
// timetable (GTFS). The Luas feed gives each stop its next trams but no tram IDs, so a tram's stops ahead are
// estimated from its live time at one stop plus these run times (see luasJourney in luas.ts).
// Usage: npm run update-luas-run-times -w @dart-times/core
// Each GTFS platform is matched to the nearest of our stops (they're all within a few tens of metres). A run time is
// the median, over every trip in the timetable, of departure to departure between consecutive stops: the time on
// the move plus the stop at the far end, so adding them up gives a tram's time at each stop along the way.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { strFromU8, unzipSync } from 'fflate';
import { LUAS_STATIONS } from '../src/stations';

const GTFS_URL = 'https://www.transportforireland.ie/transitData/Data/GTFS_LUAS.zip';
/** A platform further than this from every stop of ours isn't one of them. */
const MAX_METRES = 150;

const res = await fetch(GTFS_URL, { signal: AbortSignal.timeout(60_000) });
if (!res.ok) throw new Error(`GTFS download failed: HTTP ${res.status}`);
const zip = unzipSync(new Uint8Array(await res.arrayBuffer()), { filter: (f) => f.name === 'stops.txt' || f.name === 'stop_times.txt' });

/** Rows of a CSV file with a header, as objects. GTFS fields here have no commas or quotes. */
function rows(file: string): Record<string, string>[] {
  const [header, ...lines] = strFromU8(zip[file]!).replace(/^﻿/, '').trim().split(/\r?\n/);
  const keys = header!.split(',');
  return lines.map((line) => Object.fromEntries(line.split(',').map((v, i) => [keys[i], v])));
}

const metres = (lat1: number, lon1: number, lat2: number, lon2: number) =>
  Math.hypot((lat2 - lat1) * 111_320, (lon2 - lon1) * 111_320 * Math.cos((lat1 * Math.PI) / 180));

const codeOf = new Map<string, string>();
for (const stop of rows('stops.txt')) {
  const lat = Number(stop.stop_lat);
  const lon = Number(stop.stop_lon);
  let best: { code: string; d: number } | undefined;
  for (const s of LUAS_STATIONS) {
    const d = metres(lat, lon, s.lat!, s.lon!);
    if (!best || d < best.d) best = { code: s.code, d };
  }
  if (best && best.d <= MAX_METRES) codeOf.set(stop.stop_id!, best.code);
  else console.warn(`No stop of ours near ${stop.stop_name} (${stop.stop_id})`);
}

const seconds = (time: string) => {
  const [h, m, s] = time.split(':').map(Number) as [number, number, number];
  return h * 3600 + m * 60 + s;
};

// Each trip's stops in order, then every consecutive pair's time.
const trips = new Map<string, { seq: number; code: string; departs: number }[]>();
for (const r of rows('stop_times.txt')) {
  const code = codeOf.get(r.stop_id!);
  if (!code) continue;
  const list = trips.get(r.trip_id!) ?? [];
  list.push({ seq: Number(r.stop_sequence), code, departs: seconds(r.departure_time!) });
  trips.set(r.trip_id!, list);
}
const samples = new Map<string, number[]>();
for (const stops of trips.values()) {
  stops.sort((a, b) => a.seq - b.seq);
  for (let i = 1; i < stops.length; i++) {
    const [a, b] = [stops[i - 1]!, stops[i]!];
    if (a.code === b.code || b.departs <= a.departs) continue;
    const key = `${a.code}>${b.code}`;
    samples.set(key, [...(samples.get(key) ?? []), b.departs - a.departs]);
  }
}
const median = (xs: number[]) => {
  const sorted = [...xs].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 ? sorted[mid]! : Math.round((sorted[mid - 1]! + sorted[mid]!) / 2);
};
const runTimes = Object.fromEntries([...samples].sort(([a], [b]) => a.localeCompare(b)).map(([key, xs]) => [key, median(xs)]));

const out = fileURLToPath(new URL('../src/luasRunTimes.data.ts', import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/update-luas-run-times.ts from the NTA's Luas timetable (GTFS). Do not edit by hand.
/** Seconds from leaving one Luas stop to leaving the next, keyed "FROM>TO" (each direction separately). */
export const LUAS_RUN_SECONDS: Record<string, number> = ${JSON.stringify(runTimes, null, 2)};
`,
);
console.log(`Wrote ${Object.keys(runTimes).length} run times from ${trips.size} trips to ${out}`);
